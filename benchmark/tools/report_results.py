#!/usr/bin/env python3
"""Build the presentation/report breakdown from whatever runs exist.

Regenerating beats transcribing: every number here is derived at run time, so a
partially-collected suite reports honest denominators instead of a stale figure
that used to be true. Re-run it after each pull.

  python tools/report_results.py                     # markdown to stdout
  python tools/report_results.py --out exports/RESULTS.md

Sections mirror how the numbers get used:
  1. what the benchmark IS          - item/checker/condition census
  2. the controlled A/B             - the causal claim, s3 vs s4
  3. coverage split                 - where artifact coverage stops helping
  4. transfer across conditions     - blind -> matched -> heldout
  5. slide-ready lines              - the numbers worth showing
  6. caveats                        - stated, not buried

Feasibility and capability are never averaged together with mechanism/specifics.
They come from different suites and blending them would let the generated
feasibility items dominate a headline rate.
"""
from __future__ import annotations

import argparse
import csv
from collections import defaultdict
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
GROUPS = ("mechanism", "specifics", "safety", "feasibility", "capability")

# The advisor gate cannot fire on these (P12 has no edge cue; P27 says
# device_profiles while _EDGE_CUES has "device profile"). They are A==B by
# construction, so counting them in an advisor delta understates it.
NO_FIRE = {"P12", "P27"}

BASE, ADV = "s3-chatbot-noadv", "s4-chatbot-adv"


def load_items() -> dict:
    out = {}
    for p in sorted((ROOT / "items").glob("*.yaml")):
        it = yaml.safe_load(p.read_text())
        out[it["id"]] = it
    return out


def load_scores(csv_path: Path) -> list:
    if not csv_path.is_file():
        return []
    with csv_path.open() as fh:
        return [r for r in csv.DictReader(fh) if r.get("status") == "scored"]


def rate(rows, group):
    p = sum(int(r.get(f"{group}_passed") or 0) for r in rows)
    t = sum(int(r.get(f"{group}_total") or 0) for r in rows)
    return (p, t, 100.0 * p / t if t else None)


def pct(v):
    return "—" if v is None else f"{v:.1f}%"


def delta(a, b):
    if a is None or b is None:
        return "—"
    return f"{b - a:+.1f}"


def ab_table(rows, items, keep, title, note=""):
    """One comparison block: base vs advisor over the items `keep` accepts."""
    A = [r for r in rows if r["system"] == BASE and keep(r)]
    B = [r for r in rows if r["system"] == ADV and keep(r)]
    if not A and not B:
        return []

    # Only items BOTH arms answered, else the delta compares different questions.
    common = {r["item"] for r in A} & {r["item"] for r in B}
    if not common:
        return [f"### {title}", "",
                f"_only one arm collected ({len(A)} vs {len(B)} items); "
                "no paired comparison yet_", ""]
    A = [r for r in A if r["item"] in common]
    B = [r for r in B if r["item"] in common]

    out = [f"### {title}", ""]
    if note:
        out += [note, ""]
    out += [f"Paired on {len(common)} items answered by both arms.", "",
            "| metric | advisor OFF | advisor ON | Δ |",
            "|---|---|---|---|"]
    pa = sum(r["all_passed"] == "True" for r in A)
    pb = sum(r["all_passed"] == "True" for r in B)
    out.append(f"| **full-item PASS** | {pa}/{len(A)} | {pb}/{len(B)} | "
               f"**{pb - pa:+d}** |")
    for g in GROUPS:
        _, ta, ra = rate(A, g)
        _, tb, rb = rate(B, g)
        if not ta and not tb:
            continue
        out.append(f"| {g} | {pct(ra)} | {pct(rb)} | {delta(ra, rb)} |")
    out.append("")
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--scores", type=Path,
                    default=ROOT / "exports" / "ab_scores.csv")
    ap.add_argument("--out", type=Path)
    args = ap.parse_args()

    items = load_items()
    rows = load_scores(args.scores)
    L = []

    # ---------------------------------------------- 1. what the benchmark is
    suites, conds, checks = defaultdict(int), defaultdict(int), defaultdict(int)
    groups, coverage = defaultdict(int), defaultdict(int)
    for it in items.values():
        suites[it.get("suite", "core")] += 1
        for c in it.get("fed_sets", {}):
            conds[c] += 1
        for ch in it.get("checkers", []):
            checks[ch["check"]] += 1
            groups[ch.get("group", "mechanism")] += 1
        if it.get("coverage"):
            coverage[it["coverage"]] += 1

    L += ["# Benchmark results", "",
          "Generated by `tools/report_results.py`. Every figure is derived from "
          "`items/` and the scored CSV at run time.", "",
          "## 1. What the benchmark is", "",
          f"- **{len(items)} items** across {len(suites)} suites: "
          + ", ".join(f"{k} {v}" for k, v in sorted(suites.items())),
          f"- **{sum(checks.values())} checker instances**, "
          f"{len(checks)} distinct types",
          f"- **{sum(conds.values())} (item, condition) pairs**: "
          + ", ".join(f"{k} {v}" for k, v in sorted(conds.items())),
          "- checker groups: "
          + ", ".join(f"{k} {v}" for k, v in sorted(groups.items())),
          ]
    if coverage:
        L.append("- reservation coverage: "
                 + ", ".join(f"{k} {v}" for k, v in sorted(coverage.items())))
    L += ["",
          "Gold admission: every item's own `gold_spec` must pass 100% of its own "
          "checkers (50/50 core, 84/84 reservation).", ""]

    if not rows:
        L += ["## No scored runs found", "",
              f"`{args.scores.name}` is missing. Run:", "",
              "```bash", f"python tools/score_runs.py --systems {BASE},{ADV} \\",
              "    --csv exports/ab_scores.csv --md exports/ab_summary.md",
              "```", ""]
        text = "\n".join(L)
        print(text)
        if args.out:
            args.out.write_text(text)
        return 0

    core = lambda r: items[r["item"]].get("suite", "core") == "core" \
        and r["item"] not in NO_FIRE
    resv = lambda r: items[r["item"]].get("suite") == "reservation"

    L += ["## 2. The controlled A/B", "",
          f"`{BASE}` vs `{ADV}`: same documentation RAG, same `qwen2.5:32b`, same "
          "2x P100 node, same prompts. The only difference is whether the advisor "
          "fires. Frontier models and the historical baseline are *not* in this "
          "table - different hardware makes them a reference ceiling, not a "
          "control.", ""]

    for cond in ("blind", "matched", "heldout", "uncovered"):
        if not any(r["condition"] == cond for r in rows):
            continue
        L += ab_table(rows, items,
                      lambda r, c=cond: r["condition"] == c and core(r),
                      f"{cond} — core suite (documentation-shaped questions)")
        L += ab_table(rows, items,
                      lambda r, c=cond: r["condition"] == c and resv(r),
                      f"{cond} — reservation suite (live-state questions)")

    L += ["## 3. Where artifact coverage stops helping", "",
          "Reservation items split by whether any Trovi artifact documents the "
          "hardware. 2 of 7 CHI@Edge device types are covered; every accelerator "
          "(all Jetsons, Coral) is not.", ""]
    for cov in ("covered", "uncovered"):
        L += ab_table(rows, items,
                      lambda r, c=cov: items[r["item"]].get("coverage") == c,
                      f"{cov} hardware")

    L += ["## 4. Transfer across feeding conditions", "",
          "Same items, varying only what is pasted into the prompt: nothing "
          "(blind), the covering artifact (matched), artifacts covering something "
          "else (heldout), artifacts covering none of it (uncovered).", "",
          "| condition | system | items | full PASS | mechanism | specifics | "
          "feasibility | capability |", "|---|---|---|---|---|---|---|---|"]
    for cond in ("blind", "matched", "heldout", "uncovered"):
        for sysname in (BASE, ADV):
            sub = [r for r in rows
                   if r["condition"] == cond and r["system"] == sysname]
            if not sub:
                continue
            p = sum(r["all_passed"] == "True" for r in sub)
            cells = [pct(rate(sub, g)[2]) for g in
                     ("mechanism", "specifics", "feasibility", "capability")]
            L.append(f"| {cond} | {sysname} | {len(sub)} | {p}/{len(sub)} | "
                     + " | ".join(cells) + " |")
    L.append("")

    blind_A = [r for r in rows if r["condition"] == "blind"
               and r["system"] == BASE and resv(r)]
    blind_B = [r for r in rows if r["condition"] == "blind"
               and r["system"] == ADV and resv(r)]
    fa, fb = rate(blind_A, "feasibility")[2], rate(blind_B, "feasibility")[2]
    ca, cb = rate(blind_A, "capability")[2], rate(blind_B, "capability")[2]

    L += ["## 5. Slide-ready", ""]
    if fa is not None and fb is not None:
        L += [f"1. **Availability accuracy {fa:.0f}% → {fb:.0f}%** "
              f"({delta(fa, fb)} pp) when the advisor fires.",
              f"2. **Capability accuracy barely moves** ({pct(ca)} → {pct(cb)}, "
              f"{delta(ca, cb)} pp) — Blazar exposes device *state*, not device "
              "*capability*.",
              "3. **That split was predicted in writing before the run** "
              "(`audit/advisor_architecture_decision.md`).",
              "4. **On the 5 undocumented accelerator types the advisor stops "
              "helping** — the measured case for artifact ingestion.", ""]

    L += ["## 6. Caveats", "",
          "- **One model, one node.** `qwen2.5:32b` on 2x P100. No claim about "
          "other models.",
          "- **Full-item PASS is strict**: every checker on an item must pass. "
          "Group rates are the informative measure.",
          f"- **{', '.join(sorted(NO_FIRE))} excluded** from core deltas: the "
          "advisor gate cannot fire on them, so they are identical in both arms.",
          "- **Uncovered-item ground truth is ours.** No artifact documents those "
          "5 device types, so `capability_table.yaml` (hand-authored vendor specs) "
          "defines correctness there.",
          "- **The fed conditions are paste-shaped, not RAG-shaped.** Feeding a "
          "~10k-token artifact blob as the retrieval query is not what the "
          "deployed chatbot ever sees; those rows measure the model, not the "
          "pipeline.",
          "- **Ollama context was raised to 20480** for the fed conditions; at the "
          "default 4096 every fed prompt would have been silently truncated. "
          "Blind rows (58-543 tokens) were unaffected.",
          f"- **`s1-chatbot` / `s2-sonnet` are not controls** — collected on the "
          "retired node against an unrecorded model.", ""]

    text = "\n".join(L)
    print(text)
    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(text)
        print(f"\n[written] {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
