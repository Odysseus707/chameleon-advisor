#!/usr/bin/env python3
"""build_core_items: fill and gate the derived fields of baremetal_core items.

WHAT IS AUTHORED AND WHAT IS DERIVED
  authored   id, suite, category, axis, prompt, designed_trap, trap_tags,
             target_artifact, tier_intent_by_condition, key_tokens, api_anchor,
             verification_level, expected_answer_type, gold_spec,
             gold_provenance, checkers
  derived    fed_sets, prompt_sha256, target_content_group

An item's gold is authored - that is what the `baremetal_core` suite IS - so
this tool cannot generate items. What it owns is the part a human should not be
trusted to get right ninety times: which artifacts may be fed under which
condition. See DECISION 7 below.

  python corpus_v2/tools/build_core_items.py check    # gate, writes nothing
  python corpus_v2/tools/build_core_items.py run      # fill derived fields
  python corpus_v2/tools/build_core_items.py plan     # show heldout choices

DECISION 7, AND WHY IT IS ENFORCED RATHER THAN REMEMBERED
Six repo+commit pairs back 14 artifacts whose grounding documents are
byte-identical (`content_group`). Two rules follow:

  1. never feed a same-content_group artifact as `heldout`
  2. write at most one item per content_group

The held-out condition is the benchmark's core instrument. Under held-out
feeding, "competence transfers" predicts mechanism passes while specifics fail;
"it is only lookup" predicts both fail. Feed content-identical text as heldout
and the specifics are simply PRESENT - so specifics pass, and the item scores as
evidence for transfer when the model merely read the answer. That is a false
positive in the project's own favour, which is the worst direction for a bias to
run. Effective corpus for item-writing is 82 distinct bodies, not 90.

Rule 2 stops one body being counted twice under two ids, which would weight it
double in every aggregate rate.

R4 (carry forward what you do not own) and R5 (a no-op writes nothing) apply.
"""
from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
BENCH = HERE.parent.parent
WING = BENCH / "chameleon_bench" / "data"
ARTIFACTS = WING / "artifacts"
ITEMS = WING / "items"
GROUNDING = WING / "grounding"

SUITE = "baremetal_core"

#: Fields this tool owns. Everything else in an item file is authored and is
#: carried forward untouched - the R4 rule that was violated three times.
DERIVED_FIELDS = ("fed_sets", "prompt_sha256", "target_content_group")

#: How many neighbours the held-out condition feeds.
HELDOUT_K = 3

#: Key order for a written item, matching the edge wing's items so both read
#: the same way.
KEY_ORDER = [
    "id", "version", "suite", "category", "axis", "prompt", "prompt_sha256",
    "designed_trap", "trap_tags", "target_artifact", "target_content_group",
    "fed_sets", "partial_omits", "tier_intent_by_condition", "key_tokens", "api_anchor",
    # `verification` sits with the level it qualifies. It is EVIDENCE gathered
    # by probing the testbed - not derived from the registry - so `render` must
    # carry it rather than drop it: a key absent from KEY_ORDER is silently
    # discarded, and one `build_core_items.py run` would erase every live-
    # execution record in the bank.
    "verification_level", "verification",
    "exec_expect", "expected_answer_type", "gold_spec",
    "gold_provenance", "checkers",
]


def load_registry() -> dict:
    recs = {}
    for p in sorted(ARTIFACTS.glob("A*.yaml")):
        r = yaml.safe_load(p.read_text())
        recs[r["id"]] = r
    if not recs:
        raise SystemExit(f"no artifact records under {ARTIFACTS}")
    return recs


def load_items() -> list[tuple[Path, dict]]:
    """Only this suite's items.

    items/ holds both wings' suites now. The reservation items are generated by
    build_reservation_items.py, have no target_artifact and no fed_sets, and
    are none of this tool's business - reading them would make every
    decision-7 check report a violation about a file it does not own.
    """
    out = []
    for p in sorted(ITEMS.glob("*.yaml")):
        d = yaml.safe_load(p.read_text())
        if d.get("suite") == SUITE:
            out.append((p, d))
    return out


def prompt_sha256(prompt: str) -> str:
    """Provenance binding. An item's prompt is what a collected answer answered;
    editing it silently invalidates every cell already gathered under it, so the
    hash is recorded and a change to it is visible in the diff."""
    return hashlib.sha256(prompt.encode()).hexdigest()


#: The real OpenStack flavor set (P7). `flavors_observed` comes from
#: rank.FLAVOR_RE, `\b(m1\.\w+|g1\.\w+|gpu\.\w+)\b`, which also matches
#: filenames and attribute lookups: 15 of the 22 distinct values recorded
#: across the 90 artifacts are strings like "gpu.ipynb", "gpu.c", "gpu.get",
#: "gpu.lower" and "m1.addressable_shards". Shape alone cannot tell "m1.tiny"
#: from "m1.addressable_shards", so an allowlist is the only honest filter.
#:
#: The RAW field is deliberately left alone - it is an honest record of what
#: the regex saw, and rewriting an observation to match a later opinion of it
#: is how provenance dies. The filter belongs at the point of USE.
#:
#: Kept in step with advisor/artifacts/registry.py:REAL_FLAVORS by hand rather
#: than imported, for the same reason build_reservation_items keeps its own
#: port of meets(): the benchmark must not acquire a runtime dependency on the
#: system it grades. If one list changes the other has to (R2).
REAL_FLAVORS = frozenset({
    "m1.tiny", "m1.small", "m1.medium", "m1.large", "m1.xlarge", "m1.xxlarge",
    "g1.h100",
})


def _similarity(a: dict, b: dict) -> tuple:
    """How plausibly a retrieval system would return `b` when asked about `a`.

    Held-out feeding is meant to model "retrieval brought back neighbours but
    not the right document". Feeding three arbitrary artifacts would instead
    model "retrieval returned noise", which is a different and much easier
    claim to beat. Ranked, not scored: ties break on id so the choice is
    reproducible.
    """
    def overlap(field):
        va, vb = set(a.get(field) or []), set(b.get(field) or [])
        if field == "flavors_observed":
            va, vb = va & REAL_FLAVORS, vb & REAL_FLAVORS
        return len(va & vb)
    return (
        a.get("api_family") == b.get("api_family"),
        overlap("node_types_observed") + overlap("flavors_observed"),
        overlap("site_observed"),
        overlap("workload_tags"),
        overlap("resource_tags"),
        a.get("record_type") == b.get("record_type"),
    )


def _covers(tokens, fed, recs) -> bool:
    if not tokens:
        return True
    text = "\n".join((GROUNDING / f"{a}.md").read_text() for a in fed)
    return all(t in text for t in tokens)


def heldout_for(item: dict, target_ids: list[str], recs: dict,
                k: int = HELDOUT_K) -> list[str]:
    """Artifacts that show the GRAMMAR but not the ANSWER.

    This is the benchmark's core instrument, and getting it wrong is the one
    error that flatters us. The handoff states the prediction it has to make
    testable: under held-out feeding, "competence transfers" predicts MECHANISM
    passes while SPECIFICS fail, and "it is only lookup" predicts both fail.
    Neither prediction is falsifiable unless the fed set actually has that
    shape - mechanism present, specifics absent.

    Ranking purely by similarity does the opposite. The most similar artifacts
    are the ones most likely to name the same node type and site, so the
    "wrong artifact" condition quietly hands over the right facts: three of the
    first eight items computed to T1 under heldout, meaning the answer was
    fully present. Such an item scores as evidence of transfer when the model
    simply read it.

    So: exclude content-identical bodies, exclude anything naming ANY of the
    item's specifics, then rank the survivors by similarity and prefer sets
    that do cover the mechanism.
    """
    banned = {recs[t]["content_group"] for t in target_ids}
    primary = recs[target_ids[0]]
    kt = item.get("key_tokens") or {}
    specifics = list(kt.get("specifics") or [])

    pool = [r for r in recs.values() if r["content_group"] not in banned]

    # Hard filter: an artifact naming any specific is disqualified outright.
    # Not a ranking penalty - one leaked image string is enough to make the
    # specifics half of the prediction untestable.
    clean = [r for r in pool
             if not any(tok in (GROUNDING / f"{r['id']}.md").read_text()
                        for tok in specifics)] if specifics else pool
    if len(clean) >= k:
        pool = clean

    pool.sort(key=lambda r: (_similarity(primary, r), -int(r["id"][1:])),
              reverse=True)

    chosen, used = [], set(banned)
    for r in pool:
        if r["content_group"] in used:
            continue
        used.add(r["content_group"])
        chosen.append(r["id"])
        if len(chosen) == k:
            break
    return sorted(chosen, key=lambda i: int(i[1:]))


def derive(item: dict, recs: dict) -> dict:
    targets = item["target_artifact"]
    missing = [t for t in targets if t not in recs]
    if missing:
        raise SystemExit(f"{item['id']}: unknown target_artifact {missing}")
    groups = sorted({recs[t]["content_group"] for t in targets})
    return {
        "prompt_sha256": prompt_sha256(item["prompt"]),
        "target_content_group": groups[0] if len(groups) == 1 else groups,
        "fed_sets": fed_sets_for(item, targets, recs),
    }


def fed_sets_for(item: dict, targets: list[str], recs: dict) -> dict:
    """blind / matched / heldout, plus `partial` on composition items.

    `partial` feeds a STRICT SUBSET of the artifacts the answer needs. It is the
    other half of the instrument: `heldout` asks "can it answer from the wrong
    artifacts", `partial` asks "can it answer from too few of the right ones".
    Only the second one distinguishes composing an answer from looking it up -
    under `heldout` a lookup system and a composing system both fail, but under
    `partial` a composing system should still reach the answer and a lookup
    system cannot.

    WHICH subset is per-item and authored, via `partial_omits`. There is no one
    right answer and a fixed rule would make the condition mean different things
    on different items without saying so:

      omit the artifact holding the SPECIFICS -> the system is given the grammar
        and must supply the hardware literal. Tests whether the literal was
        learned or merely looked up.
      omit the artifact holding the GRAMMAR -> the system is given the literals
        and must supply the lifecycle. Tests whether the reservation pattern
        generalised, which is the more common claim and the easier one.
      omit the artifact holding a RARE STAGE (teardown, floating IP, network) ->
        tests whether an uncommon step is reconstructed or dropped silently.

    Default when `partial_omits` is absent: drop the last target. Whatever the
    choice, the gate proves the result leaves a key token uncovered, so a subset
    that happens to cover everything is rejected rather than measured.
    """
    fed = {
        "blind": [],
        "matched": list(targets),
        "heldout": heldout_for(item, targets, recs),
    }
    if len(targets) > 1:
        omit = item.get("partial_omits") or [targets[-1]]
        unknown = [a for a in omit if a not in targets]
        if unknown:
            raise SystemExit(
                f"{item['id']}: partial_omits names {unknown}, which is not a "
                f"target of this item (targets: {targets}).")
        fed["partial"] = [a for a in targets if a not in omit]
    return fed


def uncovered_tokens(item: dict, fed: list[str], recs: dict) -> list[str]:
    """Key tokens absent from the concatenated grounding of `fed`.

    Same notion of coverage tier_assign uses, so "partial is insufficient" and
    "tier_assign calls this T4-under-partial" cannot disagree.
    """
    text = "\n".join((GROUNDING / f"{a}.md").read_text() for a in fed)
    kt = item.get("key_tokens") or {}
    want = list(kt.get("mechanism") or []) + list(kt.get("specifics") or [])
    return [t for t in want if t not in text]


# ------------------------------------------------------------------- the gate

def violations(items: list[tuple[Path, dict]], recs: dict) -> list[str]:
    """Every way a set of items can break decision 7 or its own provenance."""
    bad = []
    seen_group: dict[str, str] = {}

    for path, item in items:
        # `or`, not dict.get's default: the default is evaluated eagerly, so
        # the fallback would deref `path` even when the id is present.
        iid = item.get("id") or (path.name if path else "<unnamed>")

        if item.get("suite") != SUITE:
            bad.append(f"{iid}: suite is {item.get('suite')!r}, expected {SUITE!r}")

        targets = item.get("target_artifact") or []
        if not targets:
            bad.append(f"{iid}: no target_artifact")
            continue
        unknown = [t for t in targets if t not in recs]
        if unknown:
            bad.append(f"{iid}: unknown target_artifact {unknown}")
            continue

        tgroups = {recs[t]["content_group"] for t in targets}

        # RULE 1 - no content-identical artifact in heldout.
        for cond, fed in (item.get("fed_sets") or {}).items():
            if cond != "heldout":
                continue
            for a in fed:
                if a not in recs:
                    bad.append(f"{iid}: heldout names unknown artifact {a}")
                elif recs[a]["content_group"] in tgroups:
                    bad.append(
                        f"{iid}: heldout feeds {a}, whose grounding is "
                        f"byte-identical to target {sorted(targets)} "
                        f"(content_group {recs[a]['content_group']}). The "
                        "specifics would be present, so a specifics pass would "
                        "read as transfer when the model simply read them.")

        # RULE 1b - the heldout set must be internally distinct too.
        for cond, fed in (item.get("fed_sets") or {}).items():
            if cond != "heldout":
                continue
            seen: dict[str, str] = {}
            for a in fed:
                if a not in recs:
                    continue
                g = recs[a]["content_group"]
                if g in seen:
                    bad.append(
                        f"{iid}: heldout feeds both {seen[g]} and {a}, which "
                        f"have byte-identical grounding (content_group {g}). "
                        "The condition then feeds fewer distinct bodies than "
                        "fed_sets claims.")
                else:
                    seen[g] = a

        # RULE 4 - heldout must not hand over the specifics.
        heldout = (item.get("fed_sets") or {}).get("heldout") or []
        spec = (item.get("key_tokens") or {}).get("specifics") or []
        if heldout and spec and all(a in recs for a in heldout):
            leaked = [t for t in spec
                      if any(t in (GROUNDING / f"{a}.md").read_text()
                             for a in heldout)]
            if leaked:
                bad.append(
                    f"{iid}: heldout {heldout} names specifics {leaked}. The "
                    "held-out condition then contains the answer, so a "
                    "specifics pass proves nothing about transfer - it is the "
                    "false positive that runs in our own favour.")

        # RULE 3 - `partial` must be a strict subset, and provably insufficient.
        fed = item.get("fed_sets") or {}
        if "partial" in fed:
            part, matched = set(fed["partial"]), set(fed.get("matched") or [])
            if not part or not part < matched:
                bad.append(
                    f"{iid}: partial {sorted(part)} is not a strict non-empty "
                    f"subset of matched {sorted(matched)}")
            else:
                missing = uncovered_tokens(item, fed["partial"], recs)
                if not missing:
                    bad.append(
                        f"{iid}: partial {sorted(part)} already covers every key "
                        "token, so it is `matched` under another name and the "
                        "item cannot show composition. Either the item does not "
                        "need its second artifact, or its key_tokens do not name "
                        "what the second artifact contributes.")

        # RULE 2 - at most one item per content_group.
        for g in sorted(tgroups):
            if g in seen_group:
                bad.append(
                    f"{iid}: content_group {g} is already targeted by "
                    f"{seen_group[g]}; one body must not be counted twice.")
            else:
                seen_group[g] = iid

        # provenance
        if item.get("prompt_sha256") != prompt_sha256(item.get("prompt", "")):
            bad.append(f"{iid}: prompt_sha256 does not match the prompt "
                       "(prompt edited without re-running this tool)")

    return bad


# ------------------------------------------------------------------ rendering

class _BlockDumper(yaml.SafeDumper):
    """Keeps multi-line strings as literal blocks.

    Without this, safe_dump folds gold_spec into one escaped line and the gold -
    the thing a human has to read to decide whether the item is fair - becomes
    unreviewable. The edge wing's items use `gold_spec: |`; matching that is
    what lets the two wings be diffed against each other by eye.
    """


def _str_representer(dumper, data):
    if "\n" in data:
        return dumper.represent_scalar("tag:yaml.org,2002:str", data, style="|")
    return dumper.represent_scalar("tag:yaml.org,2002:str", data)


_BlockDumper.add_representer(str, _str_representer)


def render(item: dict) -> str:
    ordered = {k: item[k] for k in KEY_ORDER if k in item}
    ordered.update({k: v for k, v in item.items() if k not in KEY_ORDER})
    return yaml.dump(ordered, Dumper=_BlockDumper, sort_keys=False, width=100,
                     default_flow_style=False, allow_unicode=True)


def run(write: bool) -> int:
    recs = load_registry()
    items = load_items()
    if not items:
        raise SystemExit(
            f"no items under {ITEMS}. Refusing to report a clean gate over an "
            "empty set - that reads exactly like a gate that passed.")

    changed = []
    for path, item in items:
        item.update(derive(item, recs))          # R4: update, never rebuild
        new = render(item)
        if new != path.read_text():
            changed.append(path.name)
            if write:
                path.write_text(new)

    bad = violations(load_items() if write else items, recs)
    for b in bad:
        print("  x", b)
    n = len(items)
    print(f"\n{n} item(s); {len(changed)} record(s) updated"
          f"{' (dry run)' if not write and changed else ''}; "
          f"{len(bad)} violation(s)")
    if changed and not write:
        print("  would rewrite:", ", ".join(changed))
    return 1 if bad else 0


def plan() -> int:
    recs = load_registry()
    for path, item in load_items():
        h = heldout_for(item, item["target_artifact"], recs)
        tg = {t: recs[t]["content_group"] for t in item["target_artifact"]}
        print(f"{item['id']:<7} target={tg}  heldout={h}")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("mode", choices=["check", "run", "plan"])
    args = ap.parse_args()
    if args.mode == "plan":
        return plan()
    return run(write=args.mode == "run")


if __name__ == "__main__":
    sys.exit(main())
